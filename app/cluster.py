def k8s():
    """Read kubeconfig from named volume and rewrite only server address for Compose DNS."""
    if not Path(KUBECONFIG).is_file():
        raise RuntimeError('K3s kubeconfig not ready yet. Please allow first startup to finish.')
    cfg = client.Configuration()
    config.load_kube_config(config_file=KUBECONFIG, client_configuration=cfg)
    cfg.host = K3S_HOST  # tls-san=k3s is set on k3s server
    api = client.ApiClient(configuration=cfg)
    return client.CoreV1Api(api), client.AppsV1Api(api), client.AutoscalingV2Api(api)


def apply_one(getter, creator, patcher, name, obj):
    """Create if missing; never overwrite an existing resource on restart."""
    try:
        getter(name)
        return False
    except ApiException as exc:
        if exc.status != 404:
            raise
    try:
        creator(obj)
        return True
    except ApiException as exc:
        if exc.status == 409:
            return False
        raise


def configmap(name, data):
    return client.V1ConfigMap(metadata=client.V1ObjectMeta(name=name, labels={'app': 'kics-demo'}), data=data)


def deployment(track, version):
    name = 'kics-' + track
    labels = {'app': 'kics-demo', 'track': track}
    container = client.V1Container(
        name='web', image=WEB_IMAGE, image_pull_policy='IfNotPresent',
        ports=[client.V1ContainerPort(container_port=80)],
        resources=client.V1ResourceRequirements(requests={'cpu': '30m', 'memory': '35Mi'}, limits={'cpu': '300m', 'memory': '160Mi'}),
        readiness_probe=client.V1Probe(tcp_socket=client.V1TCPSocketAction(port=80), initial_delay_seconds=3, period_seconds=5),
        liveness_probe=client.V1Probe(tcp_socket=client.V1TCPSocketAction(port=80), initial_delay_seconds=15, period_seconds=10),
        volume_mounts=[client.V1VolumeMount(name='page', mount_path='/usr/share/nginx/html/index.html', sub_path='index.html', read_only=True)]
    )
    return client.V1Deployment(
        metadata=client.V1ObjectMeta(name=name, labels=labels),
        spec=client.V1DeploymentSpec(replicas=1, revision_history_limit=5, selector=client.V1LabelSelector(match_labels=labels),
            strategy=client.V1DeploymentStrategy(type='RollingUpdate', rolling_update=client.V1RollingUpdateDeployment(max_surge=1, max_unavailable=0)),
            template=client.V1PodTemplateSpec(metadata=client.V1ObjectMeta(labels=labels, annotations={'kics.lab/release': version}),
                spec=client.V1PodSpec(containers=[container], volumes=[client.V1Volume(name='page', config_map=client.V1ConfigMapVolumeSource(name=f'kics-{track}-{version}', items=[client.V1KeyToPath(key='index.html', path='index.html')]))]))))


def service(track):
    return client.V1Service(metadata=client.V1ObjectMeta(name='kics-'+track, labels={'app': 'kics-demo'}),
        spec=client.V1ServiceSpec(type='ClusterIP', selector={'app': 'kics-demo', 'track': track}, ports=[client.V1ServicePort(name='http', port=80, target_port=80)]))


def router_deploy():
    labels = {'app': 'kics-router'}
    c = client.V1Container(
        name='nginx', image=WEB_IMAGE, image_pull_policy='IfNotPresent',
        ports=[client.V1ContainerPort(container_port=8080)],
        resources=client.V1ResourceRequirements(requests={'cpu': '25m', 'memory': '35Mi'}, limits={'cpu':'250m','memory':'160Mi'}),
        readiness_probe=client.V1Probe(http_get=client.V1HTTPGetAction(path='/healthz', port=8080), initial_delay_seconds=3, period_seconds=5),
        liveness_probe=client.V1Probe(http_get=client.V1HTTPGetAction(path='/healthz', port=8080), initial_delay_seconds=15, period_seconds=10),
        volume_mounts=[client.V1VolumeMount(name='nginx-config', mount_path='/etc/nginx/conf.d', read_only=True)])
    return client.V1Deployment(metadata=client.V1ObjectMeta(name='kics-router', labels=labels), spec=client.V1DeploymentSpec(
        replicas=2, revision_history_limit=5, selector=client.V1LabelSelector(match_labels=labels),
        strategy=client.V1DeploymentStrategy(type='RollingUpdate', rolling_update=client.V1RollingUpdateDeployment(max_surge=1,max_unavailable=0)),
        template=client.V1PodTemplateSpec(metadata=client.V1ObjectMeta(labels=labels), spec=client.V1PodSpec(containers=[c],
            volumes=[client.V1Volume(name='nginx-config', config_map=client.V1ConfigMapVolumeSource(name='kics-router-config'))]))))


def router_service():
    return client.V1Service(metadata=client.V1ObjectMeta(name='kics-router', labels={'app':'kics-router'}),
        spec=client.V1ServiceSpec(type='NodePort', selector={'app':'kics-router'}, ports=[client.V1ServicePort(name='http',port=80,target_port=8080,node_port=30080)]))


def bootstrap():
    core, apps, _ = k8s()
    try:
        core.read_namespace(NS)
    except ApiException as exc:
        if exc.status != 404: raise
        try:
            core.create_namespace(client.V1Namespace(metadata=client.V1ObjectMeta(name=NS,labels={'purpose':'kics-training'})))
        except ApiException as e:
            if e.status != 409: raise
    for track, versions in [('blue', ['v1', 'v2']), ('green', ['v2'])]:
        for ver in versions:
            name=f'kics-{track}-{ver}'
            cm=configmap(name, {'index.html':demo_html(track,ver)})
            apply_one(lambda n:core.read_namespaced_config_map(n,NS),lambda x:core.create_namespaced_config_map(NS,x),None,name,cm)
    # Create the router config first so the router pod cannot fail on missing ConfigMap.
    for name,data in [('kics-router-config', {'default.conf':nginx_conf(0)}),('kics-training-notes',{'lesson':'kubectl get pods -n kics-lab; kubectl describe deployment kics-blue -n kics-lab'})]:
        cm=configmap(name,data)
        apply_one(lambda n:core.read_namespaced_config_map(n,NS),lambda x:core.create_namespaced_config_map(NS,x),None,name,cm)
    # Not a real secret - demonstration only. Never place production secrets in training manifests.
    secret=client.V1Secret(metadata=client.V1ObjectMeta(name='kics-training-example'),string_data={'description':'demo-only-not-a-password'},type='Opaque')
    apply_one(lambda n:core.read_namespaced_secret(n,NS),lambda x:core.create_namespaced_secret(NS,x),None,'kics-training-example',secret)
    for track, ver in [('blue','v1'),('green','v2')]:
        name='kics-'+track
        obj=deployment(track,ver)
        apply_one(lambda n:apps.read_namespaced_deployment(n,NS),lambda x:apps.create_namespaced_deployment(NS,x),None,name,obj)
        obj=service(track)
        apply_one(lambda n:core.read_namespaced_service(n,NS),lambda x:core.create_namespaced_service(NS,x),None,name,obj)
    apply_one(lambda n:apps.read_namespaced_deployment(n,NS),lambda x:apps.create_namespaced_deployment(NS,x),None,'kics-router',router_deploy())
    apply_one(lambda n:core.read_namespaced_service(n,NS),lambda x:core.create_namespaced_service(NS,x),None,'kics-router',router_service())
    return True


def set_traffic(percent):
    if percent not in ALLOWED_WEIGHTS: raise ValueError('Invalid traffic split')
    core, apps, _ = k8s()
    core.patch_namespaced_config_map('kics-router-config',NS,{'data':{'default.conf':nginx_conf(percent)}})
    # Projected configmap updates are asynchronous: restart both router pods to load it deterministically.
    apps.patch_namespaced_deployment('kics-router',NS,{
        'spec':{'template':{'metadata':{'annotations':{'kics.lab/reloaded': datetime.datetime.now(datetime.timezone.utc).isoformat()}}}}
    })
    return percent


def get_traffic():
    core, _, _=k8s()
    raw=core.read_namespaced_config_map('kics-router-config',NS).data.get('default.conf','')
    import re
    match=re.search(r'kics-green\.kics-lab\.svc\.cluster\.local:80 weight=(\d+)',raw)
    if match:return int(match.group(1))
    return 100 if 'kics-green.kics-lab.svc.cluster.local:80' in raw else 0


def change_release(ver):
    if ver not in ('v1','v2'):raise ValueError('Only v1/v2 are supported')
    _,apps,_=k8s()
    # Switch immutable ConfigMap reference in the Pod template => real rolling update.
    apps.patch_namespaced_deployment('kics-blue',NS,{'spec':{'template':{
        'metadata':{'annotations':{'kics.lab/release':ver,'kics.lab/redeploy':str(time.time_ns())}},
        'spec':{'volumes':[{'name':'page','configMap':{'name':'kics-blue-'+ver,'items':[{'key':'index.html','path':'index.html'}]}}]}
    }}})
    return ver


def scale(track,replicas):
    if track not in ('blue','green') or not 1<=replicas<=4: raise ValueError('Invalid scaling parameters')
    _,apps,auto=k8s()
    # Do not fight HPA: manual scaling is disabled while an autoscaler exists.
    try:
        auto.read_namespaced_horizontal_pod_autoscaler('kics-'+track,NS)
        raise ValueError('Disable HPA before manual scaling this deployment')
    except ApiException as e:
        if e.status!=404: raise
    apps.patch_namespaced_deployment_scale('kics-'+track,NS,{'spec':{'replicas':replicas}})
    return replicas


def restart(name):
    if name not in ('kics-blue','kics-green','kics-router'):raise ValueError('Deployment not allowed')
    _,apps,_=k8s()
    apps.patch_namespaced_deployment(name,NS,{'spec':{'template':{'metadata':{'annotations':{'kics.lab/restarted':datetime.datetime.now(datetime.timezone.utc).isoformat()}}}}})
    return name


def hpa(enable):
    _,_,auto=k8s()
    name='kics-blue'
    if enable:
        body=client.V2HorizontalPodAutoscaler(metadata=client.V1ObjectMeta(name=name),spec=client.V2HorizontalPodAutoscalerSpec(
            scale_target_ref=client.V2CrossVersionObjectReference(api_version='apps/v1',kind='Deployment',name=name), min_replicas=1,max_replicas=3,
            metrics=[client.V2MetricSpec(type='Resource',resource=client.V2ResourceMetricSource(name='cpu', target=client.V2MetricTarget(type='Utilization',average_utilization=60)))]))
        try: auto.create_namespaced_horizontal_pod_autoscaler(NS,body)
        except ApiException as exc:
            if exc.status !=409:raise
    else:
        try:auto.delete_namespaced_horizontal_pod_autoscaler(name,NS)
        except ApiException as exc:
            if exc.status !=404:raise
    return enable


def state():
    core, apps, auto=k8s()
    pods=core.list_namespaced_pod(NS).items
    depl=apps.list_namespaced_deployment(NS).items
    svcs=core.list_namespaced_service(NS).items
    try: hpas=auto.list_namespaced_horizontal_pod_autoscaler(NS).items
    except ApiException: hpas=[]
    def pod_item(p):
        return {'name':p.metadata.name,'status':p.status.phase or 'Unknown', 'ready': all(x.ready for x in (p.status.container_statuses or [])) and bool(p.status.container_statuses),
            'track':(p.metadata.labels or {}).get('track','router'), 'restarts':sum(x.restart_count for x in (p.status.container_statuses or [])), 'node':p.spec.node_name or 'scheduling'}
    return {'connected':True,'namespace':NS, 'traffic_green':get_traffic(),'pods':[pod_item(p) for p in pods],
        'deployments':[{'name':d.metadata.name,'desired':d.spec.replicas or 0,'ready':d.status.ready_replicas or 0,'available':d.status.available_replicas or 0, 'release':(d.spec.template.metadata.annotations or {}).get('kics.lab/release','-')} for d in depl],
        'services':[{'name':s.metadata.name,'type':s.spec.type,'port':s.spec.ports[0].port if s.spec.ports else None} for s in svcs],
        'hpa_enabled':bool(hpas), 'ready_pods':sum(pod_item(x)['ready'] for x in pods),'total_pods':len(pods)}


def inspect(section):
    core,apps,auto=k8s()
    if section=='nodes':
        return [{'name':x.metadata.name,'ready':any(c.type=='Ready' and c.status=='True' for c in x.status.conditions or []),'version':x.status.node_info.kubelet_version} for x in core.list_node().items]
    if section=='namespaces': return [{'name':x.metadata.name,'phase':x.status.phase} for x in core.list_namespace().items]
    if section=='pods': return [{'name':p.metadata.name,'phase':p.status.phase,'ip':p.status.pod_ip,'node':p.spec.node_name} for p in core.list_namespaced_pod(NS).items]
    if section=='deployments':return [{'name':d.metadata.name,'desired':d.spec.replicas,'available':d.status.available_replicas or 0,'strategy':d.spec.strategy.type} for d in apps.list_namespaced_deployment(NS).items]
    if section=='services':return [{'name':s.metadata.name,'type':s.spec.type,'cluster_ip':s.spec.cluster_ip,'ports':[p.port for p in s.spec.ports]} for s in core.list_namespaced_service(NS).items]
    if section=='replicasets':return [{'name':r.metadata.name,'desired':r.spec.replicas,'ready':r.status.ready_replicas or 0} for r in apps.list_namespaced_replica_set(NS).items]
    if section=='configmaps':return [{'name':c.metadata.name,'keys':list(c.data or {})} for c in core.list_namespaced_config_map(NS).items]
    if section=='secrets':return [{'name':s.metadata.name,'type':s.type,'data':'[redacted]'} for s in core.list_namespaced_secret(NS).items]
    if section=='events':return [{'reason':e.reason,'message':(e.message or '')[:230],'object':e.involved_object.name,'type':e.type} for e in core.list_namespaced_event(NS,limit=40).items]
    if section=='hpa':return [{'name':x.metadata.name,'min':x.spec.min_replicas,'max':x.spec.max_replicas,'current':x.status.current_replicas,'desired':x.status.desired_replicas} for x in auto.list_namespaced_horizontal_pod_autoscaler(NS).items]
    if section=='top':
        custom=client.CustomObjectsApi(core.api_client)
        data=custom.list_namespaced_custom_object('metrics.k8s.io','v1beta1',NS,'pods')
        return [{'pod':p['metadata']['name'],'containers':[{ 'name':c['name'], **c['usage']} for c in p['containers']]} for p in data.get('items',[])]
    raise ValueError('Inspection target not allowed')


def logs(target):
    if target not in ('blue','green','router'):raise ValueError('Target not allowed')
    core,_,_=k8s()
    selector='app=kics-router' if target=='router' else 'app=kics-demo,track='+target
    pods=core.list_namespaced_pod(NS,label_selector=selector).items
    if not pods: return 'No pods found yet.'
    name=pods[0].metadata.name
    return f'Pod: {name}\n\n'+core.read_namespaced_pod_log(name,NS,tail_lines=80,timestamps=True)


def describe(target):
    if target not in ('blue','green','router'):raise ValueError('Target not allowed')
    _,apps,_=k8s()
    d=apps.read_namespaced_deployment('kics-'+target,NS)
    return {'name':d.metadata.name,'annotations':d.spec.template.metadata.annotations or {},'strategy':d.spec.strategy.type,
        'selector':d.spec.selector.match_labels,'containers':[{'image':x.image,'resources':x.resources.to_dict()} for x in d.spec.template.spec.containers],
        'desired':d.spec.replicas,'available':d.status.available_replicas or 0,'generation':d.metadata.generation}
