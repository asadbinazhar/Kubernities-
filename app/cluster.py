"""Safe, predefined Kubernetes lab operations. No arbitrary shell is exposed to browsers."""
import datetime
import os
import time
from pathlib import Path

from kubernetes import client, config
from kubernetes.client.rest import ApiException

NS = 'kics-lab'
KUBECONFIG = os.environ.get('KUBECONFIG', '/secrets/kubeconfig.yaml')
K3S_HOST = os.environ.get('K3S_API_HOST', 'https://k3s:6443')
WEB_IMAGE = os.environ.get('LAB_NGINX_IMAGE', 'nginx:1.29-alpine')
ALLOWED_WEIGHTS = {0, 10, 25, 50, 75, 90, 100}


def nginx_conf(percent):
    """Nginx upstream weights are request-balancing approximations, NOT guaranteed counts."""
    if percent not in ALLOWED_WEIGHTS:
        raise ValueError('Canary percentage not supported')
    b = 'kics-blue.kics-lab.svc.cluster.local:80'
    g = 'kics-green.kics-lab.svc.cluster.local:80'
    if percent == 0:
        entries = f'    server {b};'
    elif percent == 100:
        entries = f'    server {g};'
    else:
        entries = f'    server {b} weight={100-percent};\n    server {g} weight={percent};'
    return f'''# Generated by the KICS teaching dashboard - do not hand edit in the lab.
upstream classroom_releases {{
{entries}
}}
server {{
    listen 8080;
    server_name _;
    location / {{
        proxy_pass http://classroom_releases;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        add_header Cache-Control "no-store" always;
    }}
    location = /healthz {{ return 200 "ready\\n"; }}
}}
'''


